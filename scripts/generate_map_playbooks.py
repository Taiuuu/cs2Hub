def js_quote(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\\"').replace('\n', '\\n') + '"'


def render_value(value: Any, indent: int = 0) -> str:
    spacing = '  ' * indent
    if isinstance(value, str):
        return js_quote(value)
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        if not value:
            return '[]'
        if all(not isinstance(item, (dict, list)) for item in value):
            return '[' + ', '.join(render_value(item) for item in value) + ']'
        return '[\n' + ',\n'.join(spacing + '  ' + render_value(item, indent + 1) for item in value) + '\n' + spacing + ']'
    if isinstance(value, dict):
        return '{\n' + ',\n'.join(spacing + '  ' + f'{key}: {render_value(val, indent + 1)}' for key, val in value.items()) + '\n' + spacing + '}'
    raise TypeError(f'Unsupported type: {type(value)}')


def write_ts(path: Path, name: str, export_type: str, payload: Any) -> None:
    path.write_text(
        f'import type {{ {export_type} }} from "../core/types";\n\nexport const {name}: {export_type} = {render_value(payload)}\n',
        encoding='utf-8',
    )


def write_strat_module(path: Path, name: str, strats: list[dict[str, Any]]) -> None:
    core_import = "../core" if path.parent.name != "strats" else "../../core"
    lines = [
        f'import type {{ StratDetail }} from "{core_import}/types";',
        f'import {{ createStrat, fillRole }} from "{core_import}/stratTemplates";',
        f'import {{ sharedRoles }} from "{core_import}/sharedRoles";',
        '',
        f'export const {name}: StratDetail[] = [',
    ]
    for strat in strats:
        lines.append('  createStrat({')
        for key, value in strat.items():
            if key == 'roles':
                continue
            if key == 'category' and isinstance(value, str):
                value = CATEGORY_MAP.get(value, value)
            lines.append(f'    {key}: {render_value(value, 2)},')
        lines.append('    roles: {')
        for role_name, role_payload in strat.get('roles', {}).items():
            lines.append(
                f'      {role_name}: fillRole({render_value(role_payload, 3)}, sharedRoles.{role_name}),'  # type: ignore
            )
        lines.append('    },')
        lines.append('  }),')
    lines.append('];')
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')


