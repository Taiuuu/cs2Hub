def update_maps_index() -> None:
    map_ids = sorted(
        [folder.name for folder in MAP_ROOT.iterdir() if folder.is_dir() and folder.name != 'core' and (folder / 'index.ts').exists()]
    )
    imports = [f'import {{ {map_id}Map }} from "./{map_id}";' for map_id in map_ids]
    exports = ', '.join(f'{map_id}Map' for map_id in map_ids)
    table = [
        'export const allMaps = [' + exports + '];',
        '',
        'export const mapsById = allMaps.reduce((acc, map) => {',
        '  acc[map.id] = map;',
        '  return acc;',
        '}, {} as Record<string, typeof allMaps[number]>);',
        '',
        'export { ' + exports + ' };',
    ]
    (MAP_ROOT / 'index.ts').write_text('\n'.join(imports + [''] + table) + '\n', encoding='utf-8')


def main() -> None:
    MAP_ROOT.mkdir(parents=True, exist_ok=True)
    for map_id, payload in MAPS.items():
        folder = MAP_ROOT / map_id
        strat_folder = folder / 'strats'
        strat_folder.mkdir(parents=True, exist_ok=True)
        folder.mkdir(parents=True, exist_ok=True)

        write_ts(folder / 'philosophy.ts', f'{map_id}Philosophy', 'MapPhilosophy', payload['philosophy'])
        write_ts(folder / 'callouts.ts', f'{map_id}Callouts', 'MapCallouts', payload['callouts'])
        write_ts(folder / 'fundamentals.ts', f'{map_id}Fundamentals', 'MapFundamentals', payload['fundamentals'])

        write_strat_module(folder / 'defaults.ts', f'{map_id}Defaults', payload['defaults'])
        write_strat_module(folder / 'protocols.ts', f'{map_id}Protocols', payload['protocols'])
        write_strat_module(folder / 'retakes.ts', f'{map_id}Retakes', payload['retakes'])
        write_strat_module(folder / 'reaggressions.ts', f'{map_id}Reaggressions', payload['reaggressions'])
        write_strat_module(folder / 'antiEco.ts', f'{map_id}AntiEco', payload['antiEco'])
        write_strat_module(strat_folder / 'pistol.ts', f'{map_id}PistolStrats', payload['pistol'])
        write_strat_module(strat_folder / 'eco.ts', f'{map_id}EcoStrats', payload['eco'])
        write_strat_module(strat_folder / 'force.ts', f'{map_id}ForceStrats', payload['force'])
        write_strat_module(strat_folder / 'buy.ts', f'{map_id}BuyStrats', payload['buy'])
        write_strat_module(strat_folder / 'midRound.ts', f'{map_id}MidRoundStrats', payload['midRound'])

        write_map_index(map_id)

    update_maps_index()


if __name__ == '__main__':
    main()
